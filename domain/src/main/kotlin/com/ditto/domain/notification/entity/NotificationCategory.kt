package com.ditto.domain.notification.entity

/**
 * 알림 센터 상단 필터 칩(피그마 7.2) — 전체 / 매칭 / 대화 / 시스템.
 *
 * "전체"는 값이 아니라 **필터 없음**이다(파라미터를 생략한다). 값으로 두면 목록 조회가 전체와
 * 나머지를 다르게 다뤄야 하고, 새 카테고리가 생길 때 전체에 포함시키는 것을 잊을 수 있다.
 *
 * 컬럼으로 저장하지 않는다 — [NotificationType.category]에서 파생된다. 저장하면 타입과 카테고리가
 * 어긋난 행이 생길 수 있고, 분류를 고칠 때 기존 행을 모두 갱신해야 한다.
 */
enum class NotificationCategory {

    /** 매칭 결과·그룹 구성·재매칭 성사·만남 평가 요청 — 매칭 흐름에서 나오는 알림 */
    MATCHING,

    /** 새 메시지·채팅 종료 임박 — 대화방에서 나오는 알림 */
    CHAT,

    /** 공지·업데이트 안내 — 운영이 보내는 알림 */
    SYSTEM,
}
